/// Rebuilds a `CommonLocation` timestamp from the prototype's separate
/// `date` + `time` strings (e.g. '2026-04-11' + '09:15 AM').
DateTime _at(String date, String time) {
  final m = RegExp(
    r'^(\d{1,2}):(\d{2})\s*(AM|PM)$',
    caseSensitive: false,
  ).firstMatch(time.trim());
  final base = DateTime.parse(date);
  if (m == null) return base;
  var hour = int.parse(m.group(1)!) % 12;
  if (m.group(3)!.toUpperCase() == 'PM') hour += 12;
  return DateTime(
    base.year,
    base.month,
    base.day,
    hour,
    int.parse(m.group(2)!),
  );
}

